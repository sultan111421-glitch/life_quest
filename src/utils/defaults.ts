export function buildSeedDailyLogs(
  todayKey: string,
  activities: ActivityDefinition[],
  computeSummary: (
    acts: ActivityDefinition[],
    entries: Record<string, ActivityEntry>,
    config: LevelConfig
  ) => {
    totalXpEarned: number;
    completionPct: number;
    completedCount: number;
    totalCount: number;
  },
  config: LevelConfig = DEFAULT_LEVEL_CONFIG
): Record<string, DailyLog> {
  const logs: Record<string, DailyLog> = {};

  const patterns = [
    { studyMin: 135, exercise: 35, walk: 30, sleep: 7.5, water: 8, detox: 60, skill: 45, productive: 240, wasted: 35, note: true },
    { studyMin: 90, exercise: 25, walk: 20, sleep: 7, water: 7, detox: 45, skill: 30, productive: 180, wasted: 55, note: true },
    { studyMin: 150, exercise: 30, walk: 35, sleep: 8, water: 8, detox: 75, skill: 60, productive: 280, wasted: 25, note: true },
    { studyMin: 60, exercise: 15, walk: 25, sleep: 6.5, water: 6, detox: 30, skill: 20, productive: 120, wasted: 80, note: false },
    { studyMin: 120, exercise: 30, walk: 30, sleep: 7, water: 8, detox: 60, skill: 45, productive: 230, wasted: 40, note: true },
    { studyMin: 140, exercise: 40, walk: 30, sleep: 7.5, water: 9, detox: 90, skill: 50, productive: 270, wasted: 20, note: true },
    { studyMin: 110, exercise: 20, walk: 30, sleep: 7, water: 7, detox: 50, skill: 35, productive: 200, wasted: 45, note: true },
    { studyMin: 125, exercise: 30, walk: 25, sleep: 7.5, water: 8, detox: 60, skill: 45, productive: 245, wasted: 30, note: true },
    { studyMin: 80, exercise: 0, walk: 20, sleep: 6, water: 6, detox: 40, skill: 30, productive: 150, wasted: 65, note: false },
    { studyMin: 130, exercise: 30, walk: 35, sleep: 7.5, water: 8, detox: 65, skill: 45, productive: 250, wasted: 30, note: true },
    { studyMin: 120, exercise: 35, walk: 30, sleep: 8, water: 8, detox: 60, skill: 50, productive: 240, wasted: 25, note: true },
    { studyMin: 100, exercise: 25, walk: 30, sleep: 7, water: 7, detox: 55, skill: 40, productive: 195, wasted: 40, note: true },
    { studyMin: 125, exercise: 30, walk: 30, sleep: 7.5, water: 8, detox: 60, skill: 45, productive: 260, wasted: 25, note: true },
  ];

  patterns.forEach((p, idx) => {
    const daysAgo = patterns.length - idx;
    const dateKey = shiftDateKey(todayKey, -daysAgo);
    const entries: Record<string, ActivityEntry> = {
      study: {
        hours: Math.floor(p.studyMin / 60),
        minutes: p.studyMin % 60,
      },
      exercise: { value: p.exercise },
      walking: { value: p.walk },
      sleep: { value: p.sleep },
      water: { value: p.water },
      detox: { value: p.detox },
      skill_learning: { value: p.skill },
      personal_dev: {
        textValue: p.note ? SEED_NOTES[idx % SEED_NOTES.length] : '',
      },
      [TIME_AUDIT_ENTRY_KEY]: {
        value: p.productive,
        minutes: p.wasted,
      },
    };
    const summary = computeSummary(activities, entries, config);
    logs[dateKey] = {
      dateKey,
      entries,
      ...summary,
      updatedAtIso: new Date().toISOString(),
    };
  });

  const todayEntries: Record<string, ActivityEntry> = {
    study: { hours: 1, minutes: 0 },
    water: { value: 4 },
    [TIME_AUDIT_ENTRY_KEY]: {
      value: 60,
      minutes: 15,
    },
  };
  const todaySummary = computeSummary(activities, todayEntries, config);
  logs[todayKey] = {
    dateKey: todayKey,
    entries: todayEntries,
    ...todaySummary,
    updatedAtIso: new Date().toISOString(),
  };

  return logs;
}

