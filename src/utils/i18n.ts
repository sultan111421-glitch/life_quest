export function getLocalizedActivityTitle(
  activity: ActivityDefinition,
  lang: Language
): string {
  const core = CORE_ACTIVITY_TITLES[activity.id];
  if (core && (activity.title === core.bn || activity.title === core.en)) {
    return core[lang];
  }
  return activity.title;
}

export function getLocalizedUnitLabel(unitLabel: string, lang: Language): string {
  const mapped = UNIT_MAP[unitLabel.trim()];
  return mapped ? mapped[lang] : unitLabel;
}

export function getLocalizedDisplayName(displayName: string, lang: Language): string {
  if (displayName === 'অভিযাত্রী' || displayName === 'Adventurer') {
    return lang === 'en' ? 'Adventurer' : 'অভিযাত্রী';
  }
  return displayName;
}

